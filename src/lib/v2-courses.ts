export const v2Courses: Course[] = courses.map((course) => ({
  ...course,
  ...introductions[course.slug],
  ...centerPhoto(coursePhotos[course.slug]),
  imageFit: "cover",
}));
export const getProgram = (id: string) =>
  programs.find((program) => program.id === id);
export const getCourseProgram = (slug: string) =>
  programs.find((program) => program.courseSlugs.includes(slug));
export const getV2Course = (slug: string) =>
  v2Courses.find((course) => course.slug === slug);
export const getProgramCourses = (id: string) => {
  const program = getProgram(id);
  return program
    ? program.courseSlugs.map((slug) => getV2Course(slug)!).filter(Boolean)
    : [];
};

export const programCourseCount = (count: number) => {
  if (count === 0) return "لا توجد دورات";
  if (count === 1) return "دورة تدريبية واحدة";
  if (count === 2) return "دورتان تدريبيتان";
  return `${arabicNumber(count)} ${count <= 10 ? "دورات تدريبية" : "دورة تدريبية"}`;
};
