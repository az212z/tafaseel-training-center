function centerPhoto(id: string) {
  const photo = facilityPhotos.find((item) => item.id === id);
  if (!photo) throw new Error(`Unknown center photograph: ${id}`);
  return { image: `facility/${photo.id}.webp`, imageAlt: photo.alt };
}

